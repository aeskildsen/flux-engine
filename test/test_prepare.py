"""Tests for scripts/prepare.py: the generator of the hook input, and how the
isospin UGen sources get into the build folder. They need no build, no
network and no Faust.

Run: python3 -m unittest discover -s test -p 'test_*.py'
"""
import hashlib
import importlib.util
import io
import os
import sys
import tarfile
import tempfile
import textwrap
import unittest
from pathlib import Path

sys.dont_write_bytecode = True
_spec = importlib.util.spec_from_file_location(
    "prepare", Path(__file__).resolve().parent.parent / "scripts" / "prepare.py")
prepare = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(prepare)

ISOSPIN_CMAKE = textwrap.dedent("""\
    # Generated by flux-engine scripts/prepare.py from ugens.toml. Do not edit.
    # The UGens that flux-engine adds to SuperSonic's engine. SuperSonic's
    # dsp/scsynth/CMakeLists.txt includes this file when SCSYNTH_EXTRA_PLUGINS
    # points to it (patches/supersonic-extra-plugins.patch adds that hook).

    # The static UGens of isospin. Their isospin.cmake sets the source list
    # and the build settings of each source.
    include("${CMAKE_CURRENT_LIST_DIR}/../isospin/isospin.cmake")
    list(APPEND SCSYNTH_PLUGIN_SOURCES ${ISOSPIN_SC_STATIC_SOURCES})
    set_property(SOURCE synth/server/SC_Lib_Cintf.cpp APPEND PROPERTY
        INCLUDE_DIRECTORIES "${ISOSPIN_SC_STATIC_DIR}")

    set(SCSYNTH_EXTRA_PLUGINS_HEADER "${CMAKE_CURRENT_LIST_DIR}/extra-plugins.h")
    """)

ISOSPIN_HEADER = textwrap.dedent("""\
    // Generated by flux-engine scripts/prepare.py from ugens.toml. Do not edit.
    // The load functions of the UGens that flux-engine adds to SuperSonic's
    // engine. SC_Lib_Cintf.cpp includes this file and calls
    // SC_ExtraPlugins_Load() after the built-in plugins.
    #pragma once

    #include "isospin_sc_static.h"

    static inline void SC_ExtraPlugins_Load(InterfaceTable* table) {
        Isospin_Load(table);
    }
    """)

PIN = {"version": "0.2.0", "sha256": "0" * 64}


def make_tarball(path: Path, files: dict[str, str]) -> str:
    """Writes a release tarball with one top folder, and gives its SHA-256."""
    with tarfile.open(path, "w:gz") as tar:
        for name, text in files.items():
            data = text.encode()
            info = tarfile.TarInfo(f"isospin-sc-static-0.2.0/{name}")
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
    return hashlib.sha256(path.read_bytes()).hexdigest()


class RenderPlugins(unittest.TestCase):
    def test_isospin_entry(self):
        cmake, header = prepare.render_plugins({"isospin": PIN})
        self.assertEqual(cmake, ISOSPIN_CMAKE)
        self.assertEqual(header, ISOSPIN_HEADER)

    def test_no_ugen_name_by_hand(self):
        cmake, header = prepare.render_plugins({"isospin": PIN})
        self.assertNotIn("Woodbar", cmake + header)

    def test_empty_manifest_gives_a_load_function_with_no_calls(self):
        cmake, header = prepare.render_plugins({})
        self.assertNotIn("include(", cmake)
        self.assertIn("SCSYNTH_EXTRA_PLUGINS_HEADER", cmake)
        self.assertIn("static inline void SC_ExtraPlugins_Load(InterfaceTable* table) {\n}\n",
                      header)


class LoadManifest(unittest.TestCase):
    def load(self, text: str) -> dict:
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "ugens.toml"
            path.write_text(text)
            return prepare.load_manifest(path)

    def test_the_repository_manifest_loads(self):
        manifest = prepare.load_manifest(prepare.ROOT / "ugens.toml")
        self.assertRegex(manifest["isospin"]["sha256"], r"^[0-9a-f]{64}$")

    def test_unknown_kind(self):
        with self.assertRaisesRegex(prepare.PrepareError, "unknown entry 'faust'"):
            self.load('[faust]\nfile = "woodbar.dsp"\n')

    def test_isospin_needs_version_and_sha256(self):
        with self.assertRaisesRegex(prepare.PrepareError, "isospin.sha256"):
            self.load('[isospin]\nversion = "0.2.0"\n')

    def test_isospin_unknown_key(self):
        with self.assertRaisesRegex(prepare.PrepareError, "isospin.url"):
            self.load('[isospin]\nversion = "0.2.0"\nsha256 = ""\nurl = "x"\n')


class WriteIfChanged(unittest.TestCase):
    def test_leaves_an_unchanged_file_untouched(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "sub" / "a.h"
            self.assertTrue(prepare.write_if_changed(path, "x\n"))
            os.utime(path, (0, 0))
            self.assertFalse(prepare.write_if_changed(path, "x\n"))
            self.assertEqual(path.stat().st_mtime, 0)
            self.assertTrue(prepare.write_if_changed(path, "y\n"))
            self.assertEqual(path.read_text(), "y\n")


class ReadEnv(unittest.TestCase):
    def test_shell_style_values(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "local.env"
            path.write_text("# a comment\n\nISOSPIN_DIR=$HOME/isospin\nB='~/x'\nC=\"a b\"\n")
            values = prepare.read_env(path, {"HOME": "/home/u"})
        self.assertEqual(values, {"ISOSPIN_DIR": "/home/u/isospin", "B": "~/x", "C": "a b"})

    def test_missing_file(self):
        self.assertEqual(prepare.read_env(Path("/nonexistent/local.env"), {}), {})


class PrepareIsospin(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.tmp = Path(self._tmp.name)
        self.out = self.tmp / "build" / "isospin"
        self.downloads = self.tmp / "build" / "downloads"
        self.tarball = self.tmp / "release.tar.gz"
        self.sha256 = make_tarball(self.tarball, {"BUILDINFO": "kind=release\n",
                                                  "src/Woodbar.cpp": "// ugen\n"})
        self.env = {"ISOSPIN_URL": self.tarball.as_uri()}

    def tearDown(self):
        self._tmp.cleanup()

    def run_prepare(self, pin: dict, env: dict) -> str:
        return prepare.prepare_isospin(pin, self.out, self.downloads, env)

    def test_downloads_checks_and_unpacks_the_release(self):
        message = self.run_prepare({"version": "0.2.0", "sha256": self.sha256}, self.env)
        self.assertEqual(message, "isospin 0.2.0")
        self.assertEqual((self.out / "src" / "Woodbar.cpp").read_text(), "// ugen\n")
        self.assertEqual((self.out / ".sha256").read_text().strip(), self.sha256)
        self.assertTrue((self.downloads / "isospin-sc-static-0.2.0.tar.gz").is_file())

    def test_does_not_unpack_the_same_release_again(self):
        pin = {"version": "0.2.0", "sha256": self.sha256}
        self.run_prepare(pin, self.env)
        source = self.out / "src" / "Woodbar.cpp"
        os.utime(source, (0, 0))
        self.tarball.unlink()  # The second run must use the download.
        self.run_prepare(pin, self.env)
        self.assertEqual(source.stat().st_mtime, 0)

    def test_wrong_sha256_stops_and_keeps_no_file(self):
        with self.assertRaisesRegex(prepare.PrepareError, "does not have the SHA-256"):
            self.run_prepare({"version": "0.2.0", "sha256": "f" * 64}, self.env)
        self.assertEqual(list(self.downloads.iterdir()), [])
        self.assertFalse(self.out.exists())

    def test_empty_sha256_stops(self):
        with self.assertRaisesRegex(prepare.PrepareError, "no SHA-256"):
            self.run_prepare({"version": "0.2.0", "sha256": ""}, self.env)

    def test_environment_replaces_the_pin(self):
        env = {**self.env, "ISOSPIN_VERSION": "9.9.9", "ISOSPIN_SHA256": self.sha256}
        self.assertEqual(self.run_prepare(PIN, env), "isospin 9.9.9")
        self.assertTrue((self.downloads / "isospin-sc-static-9.9.9.tar.gz").is_file())

    def test_isospin_dir_runs_the_generator_of_the_working_copy(self):
        work = self.tmp / "isospin"
        (work / "scripts").mkdir(parents=True)
        (work / "scripts" / "build-sc-static.py").write_text(textwrap.dedent("""\
            import sys
            from pathlib import Path
            out = Path(sys.argv[sys.argv.index("--out") + 1])
            out.mkdir(parents=True, exist_ok=True)
            (out / "BUILDINFO").write_text("kind=development\\n")
            """))
        message = self.run_prepare(PIN, {"ISOSPIN_DIR": str(work)})
        self.assertIn("development build", message)
        self.assertEqual((self.out / "BUILDINFO").read_text(), "kind=development\n")

    def test_isospin_dir_stops_when_the_generator_fails(self):
        work = self.tmp / "isospin"
        (work / "scripts").mkdir(parents=True)
        (work / "scripts" / "build-sc-static.py").write_text("raise SystemExit(3)\n")
        with self.assertRaisesRegex(prepare.PrepareError, "build-sc-static.py"):
            self.run_prepare(PIN, {"ISOSPIN_DIR": str(work)})


if __name__ == "__main__":
    unittest.main()
