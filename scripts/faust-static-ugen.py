"""Turn the Faust SuperCollider UGen source into a statically linked plugin.

Faust's supercollider.cpp architecture makes a plugin for dlopen: it exports
`load`, `api_version` and `server_type`, and it names its unit struct and its
unit functions `Faust`, `Faust_Ctor` and so on. A static build links all
plugins into one binary, and these names then collide between two Faust UGens.

This script renames them, so that each UGen has its own names, and removes
the three exported functions. The entry point becomes `<Name>_Load`. Add a
call to this function in SC_Lib_Cintf.cpp.

Usage:
    faust -a supercollider.cpp -cn <Name> -ftz 1 -I <lib dir> <sketch>.dsp \
        -o raw.cpp
    faust-static-ugen.py <Name> raw.cpp <out>.cpp

<Name> must be the same as the class name given to Faust with -cn.
"""
import re
import sys


def convert(name: str, source: str) -> str:
    unit = f"{name}Unit"

    # The unit struct and its functions. The \b stops a match inside longer
    # words, and `Faust_` does not match the Faust library macros.
    source = re.sub(r"\bFaust_(\w+)", rf"{name}_\1", source)
    source = re.sub(r"\bstruct Faust\b", f"struct {unit}", source)
    source = re.sub(r"\bFaust\*", f"{unit}*", source)
    source = re.sub(r"sizeof\(Faust\)", f"sizeof({unit})", source)

    # The entry point.
    source, count = re.subn(
        r"FAUST_EXPORT void load\(InterfaceTable\*(\s*\w+)?\)",
        lambda m: f"void {name}_Load(InterfaceTable*{m.group(1) or ''})",
        source,
    )
    if count != 2:
        sys.exit(f"expected 2 load() lines (declaration and definition), found {count}")

    # api_version is exported only when SC_API_EXPORT is set. Remove the
    # declaration and the definition, each with its #ifdef guard.
    source = re.sub(
        r"#ifdef SC_API_EXPORT\n\s*FAUST_EXPORT int api_version\(void\)[^\n]*\n#endif\n",
        "",
        source,
    )

    # server_type tells the host if this is a scsynth or a supernova plugin.
    # A static plugin has no use for it.
    source = re.sub(
        r"#ifdef SUPERNOVA\s*\nextern \"C\" FAUST_EXPORT int server_type\(void\)[^\n]*\n"
        r"#else\s*\nextern \"C\" FAUST_EXPORT int server_type\(void\)[^\n]*\n#endif\n",
        "",
        source,
    )

    for leftover in ("api_version", "server_type"):
        if re.search(rf"\b{leftover}\b", source):
            sys.exit(f"{leftover} is still in the output: the architecture file changed")

    banner = (
        "// Generated by scripts/faust-static-ugen.py from Faust output. Do not edit.\n"
        "// To change the UGen, change the .dsp sketch and generate again.\n"
    )
    return banner + source


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    name, src, dst = sys.argv[1:]
    with open(src) as f:
        text = f.read()
    with open(dst, "w") as f:
        f.write(convert(name, text))


if __name__ == "__main__":
    main()
