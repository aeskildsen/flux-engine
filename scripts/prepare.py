#!/usr/bin/env python3
"""Prepare the SuperSonic submodule for a build with the flux-engine UGens.

1. Apply the patches in patches/ to the submodule (once; a second run finds
   them applied and does nothing).
2. Put the UGen sources that ugens.toml names into build/.
3. Generate the input of the SuperSonic hook from ugens.toml:
   build/plugins/extra-plugins.cmake (SCSYNTH_EXTRA_PLUGINS points to it) and
   build/plugins/extra-plugins.h. The script writes a file only when its
   content changed, so that an unchanged build compiles nothing again.

isospin: the UGen sources come from the isospin release that ugens.toml pins.
The tarball is downloaded once into build/downloads, checked against its
SHA-256 and unpacked into build/isospin. This needs no Faust.

For local development, set ISOSPIN_DIR to an isospin working copy. The
sources are then made from it with its scripts/build-sc-static.py (this needs
faust), and the build is a development build: do not release it. local.env
(not in git, shell syntax KEY=VALUE) can set ISOSPIN_DIR; the environment
has priority over local.env.

For tests, ISOSPIN_VERSION, ISOSPIN_SHA256 and ISOSPIN_URL replace the
release values (ISOSPIN_URL can be a file:// URL).

Needs Python 3.11 or later (standard library only) and git.

Usage: scripts/prepare.py
"""
import hashlib
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
PLUGINS = BUILD / "plugins"

ISOSPIN_KEYS = {"version", "sha256"}
ISOSPIN_URL = ("https://github.com/aeskildsen/isospin/releases/download/"
               "v{version}/isospin-sc-static-{version}.tar.gz")

GENERATED = "Generated by flux-engine scripts/prepare.py from ugens.toml. Do not edit."

CMAKE_HEAD = f"""\
# {GENERATED}
# The UGens that flux-engine adds to SuperSonic's engine. SuperSonic's
# dsp/scsynth/CMakeLists.txt includes this file when SCSYNTH_EXTRA_PLUGINS
# points to it (patches/supersonic-extra-plugins.patch adds that hook).
"""

CMAKE_TAIL = """\

set(SCSYNTH_EXTRA_PLUGINS_HEADER "${CMAKE_CURRENT_LIST_DIR}/extra-plugins.h")
"""

# The paths are relative to build/plugins, so the files do not depend on the
# checkout path.
CMAKE_ISOSPIN = """\

# The static UGens of isospin. Their isospin.cmake sets the source list
# and the build settings of each source.
include("${CMAKE_CURRENT_LIST_DIR}/../isospin/isospin.cmake")
list(APPEND SCSYNTH_PLUGIN_SOURCES ${ISOSPIN_SC_STATIC_SOURCES})
set_property(SOURCE synth/server/SC_Lib_Cintf.cpp APPEND PROPERTY
    INCLUDE_DIRECTORIES "${ISOSPIN_SC_STATIC_DIR}")
"""

HEADER_HEAD = f"""\
// {GENERATED}
// The load functions of the UGens that flux-engine adds to SuperSonic's
// engine. SC_Lib_Cintf.cpp includes this file and calls
// SC_ExtraPlugins_Load() after the built-in plugins.
#pragma once
"""


class PrepareError(Exception):
    """A problem that stops the build, with a message for the user."""


def load_manifest(path: Path) -> dict:
    """Reads ugens.toml and checks its entries."""
    with open(path, "rb") as f:
        manifest = tomllib.load(f)
    for kind in manifest:
        if kind != "isospin":
            raise PrepareError(f"{path.name}: unknown entry '{kind}'")
    if "isospin" in manifest:
        entry = manifest["isospin"]
        for key in sorted(ISOSPIN_KEYS - entry.keys()):
            raise PrepareError(f"{path.name}: isospin.{key} is missing")
        for key in sorted(entry.keys() - ISOSPIN_KEYS):
            raise PrepareError(f"{path.name}: isospin.{key} is not a known key")
        for key in sorted(ISOSPIN_KEYS):
            if not isinstance(entry[key], str):
                raise PrepareError(f"{path.name}: isospin.{key} must be a string")
    return manifest


def render_plugins(manifest: dict) -> tuple[str, str]:
    """Gives the text of extra-plugins.cmake and extra-plugins.h."""
    cmake = [CMAKE_HEAD]
    includes = []
    calls = []
    if "isospin" in manifest:
        cmake.append(CMAKE_ISOSPIN)
        includes.append('#include "isospin_sc_static.h"\n')
        calls.append("    Isospin_Load(table);\n")
    cmake.append(CMAKE_TAIL)
    header = [HEADER_HEAD]
    if includes:
        header += ["\n", *includes]
    header += ["\nstatic inline void SC_ExtraPlugins_Load(InterfaceTable* table) {\n",
               *calls, "}\n"]
    return "".join(cmake), "".join(header)


def write_if_changed(path: Path, text: str) -> bool:
    """Writes text to path when the file has other content. Gives True when
    it wrote."""
    if path.is_file() and path.read_text() == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return True


_VAR = re.compile(r"\$(\w+)|\$\{(\w+)\}")


def read_env(path: Path, environ: dict[str, str]) -> dict[str, str]:
    """Reads KEY=VALUE lines in shell syntax: a value in single quotes is used
    as it is; other values get $VAR, ${VAR} and a leading ~ expanded from
    environ."""
    if not path.is_file():
        return {}
    values = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        key, _, value = line.partition("=")
        if len(value) >= 2 and value[0] == value[-1] == "'":
            values[key.strip()] = value[1:-1]
            continue
        if len(value) >= 2 and value[0] == value[-1] == '"':
            value = value[1:-1]
        elif value.startswith("~"):
            value = environ.get("HOME", "~") + value[1:]
        values[key.strip()] = _VAR.sub(
            lambda m: environ.get(m.group(1) or m.group(2), ""), value)
    return values


def apply_patches(supersonic: Path, patches: Path) -> None:
    for patch in sorted(patches.glob("*.patch")):
        check = subprocess.run(["git", "-C", str(supersonic), "apply", "--reverse",
                                "--check", str(patch)], capture_output=True)
        if check.returncode == 0:
            print(f"prepare: already applied: {patch.name}")
            continue
        applied = subprocess.run(["git", "-C", str(supersonic), "apply", str(patch)])
        if applied.returncode != 0:
            raise PrepareError(f"{patch.name} does not apply to {supersonic}")
        print(f"prepare: applied: {patch.name}")


def sha256_of(path: Path) -> str:
    with open(path, "rb") as f:
        return hashlib.file_digest(f, "sha256").hexdigest()


def prepare_isospin(pin: dict, out: Path, downloads: Path, env: dict[str, str]) -> str:
    """Puts the isospin UGen sources into out: from the working copy in
    ISOSPIN_DIR, else from the pinned release. Gives a line for the log."""
    if env.get("ISOSPIN_DIR"):
        work = Path(env["ISOSPIN_DIR"]).expanduser()
        script = work / "scripts" / "build-sc-static.py"
        # build-sc-static.py writes only the files that changed, so that only
        # the changed UGens are compiled again. It also removes the .sha256
        # stamp, so the next release build unpacks the release again.
        run = subprocess.run([sys.executable, "-I", str(script), "--out", str(out)])
        if run.returncode != 0:
            raise PrepareError(f"{script} failed (exit {run.returncode})")
        return f"WARNING: development build, isospin UGens from {work}"

    version = env.get("ISOSPIN_VERSION") or pin["version"]
    sha256 = env.get("ISOSPIN_SHA256") or pin["sha256"]
    url = env.get("ISOSPIN_URL") or ISOSPIN_URL.format(version=version)
    if not sha256:
        raise PrepareError(f"ugens.toml has no SHA-256 for isospin {version} "
                           "(set ISOSPIN_DIR to build from a working copy)")
    tarball = downloads / f"isospin-sc-static-{version}.tar.gz"

    if not tarball.is_file() or sha256_of(tarball) != sha256:
        downloads.mkdir(parents=True, exist_ok=True)
        part = tarball.with_name(tarball.name + ".part")
        try:
            with urllib.request.urlopen(url) as response, open(part, "wb") as f:
                shutil.copyfileobj(response, f)
            if sha256_of(part) != sha256:
                raise PrepareError(f"{url} does not have the SHA-256 in ugens.toml")
            part.replace(tarball)
        finally:
            part.unlink(missing_ok=True)
        print(f"prepare: downloaded {tarball.name}")

    # Unpack only when the release changed, so that an unchanged build does
    # not compile the UGens again.
    stamp = out / ".sha256"
    if not stamp.is_file() or stamp.read_text().strip() != sha256:
        shutil.rmtree(out, ignore_errors=True)
        out.mkdir(parents=True)
        with tarfile.open(tarball) as tar:
            members = []
            for member in tar.getmembers():
                # The same as tar --strip-components=1.
                _, _, rest = member.name.partition("/")
                if rest:
                    member.name = rest
                    members.append(member)
            tar.extractall(out, members=members, filter="data")
        stamp.write_text(sha256 + "\n")
        print(f"prepare: unpacked {tarball.name}")
    return f"isospin {version}"


def main() -> None:
    # Keep the log lines in order with stderr and with the subprocesses, also
    # when the output goes to a pipe or a file.
    sys.stdout.reconfigure(line_buffering=True)
    env ={**read_env(ROOT / "local.env", dict(os.environ)), **os.environ}
    try:
        manifest = load_manifest(ROOT / "ugens.toml")
        apply_patches(ROOT / "supersonic", ROOT / "patches")
        if "isospin" in manifest:
            message = prepare_isospin(manifest["isospin"], BUILD / "isospin",
                                      BUILD / "downloads", env)
            print(f"prepare: {message}", file=sys.stderr if "WARNING" in message else sys.stdout)
        cmake, header = render_plugins(manifest)
        for name, text in (("extra-plugins.cmake", cmake), ("extra-plugins.h", header)):
            if write_if_changed(PLUGINS / name, text):
                print(f"prepare: wrote build/plugins/{name}")
    except PrepareError as e:
        sys.exit(f"prepare: {e}")


if __name__ == "__main__":
    main()
